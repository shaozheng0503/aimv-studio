def set_text(p, text):
    if p.runs:
        p.runs[0].text = text
        for r in p.runs[1:]:
            r.text = ""
    else:
        p.add_run(text)


d = Document(PATH)
done = set()
for p in d.paragraphs:
    t = p.text.strip()
    for i, (prefix, new) in enumerate(REPLACEMENTS):
        if i in done:
            continue
        if t.startswith(prefix):
            set_text(p, new)
            done.add(i)
            print(f"[ok] replaced #{i}: {prefix[:18]}…")
            break

missing = [REPLACEMENTS[i][0][:18] for i in range(len(REPLACEMENTS)) if i not in done]
if missing:
    print("[WARN] not matched:", missing)
else:
    d.save(PATH)
    print("saved", PATH)

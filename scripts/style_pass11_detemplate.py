def set_text(p, text):
    if p.runs:
        p.runs[0].text = text
        for r in p.runs[1:]:
            r.text = ""
    else:
        p.add_run(text)


d = Document(PATH)
done = set()
for p in d.paragraphs:
    t = p.text
    for i, (snip, new) in enumerate(R):
        if i in done:
            continue
        if snip in t:
            set_text(p, new)
            done.add(i)
            break

missing = [(i, R[i][0][:22]) for i in range(len(R)) if i not in done]
if missing:
    print("[WARN] NOT matched:", missing)
else:
    d.save(PATH)
    print("saved", PATH, "| 共替换", len(done), "段")

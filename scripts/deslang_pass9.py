def main(mode):
    d = docx.Document(SRC)
    paras = d.paragraphs
    applied = 0
    problems = []
    # 整段替换
    for idx, prefix, newtext in FULL:
        p = paras[idx]
        nonempty = [r for r in p.runs if r.text]
        cur = p.runs[0].text if p.runs else ""
        if not cur.startswith(prefix):
            problems.append(f"[FULL idx={idx}] 前缀不匹配: 期望<{prefix}> 实际<{cur[:24]}>")
            continue
        if len(nonempty) != 1:
            problems.append(f"[FULL idx={idx}] 非空 run 数={len(nonempty)} (期望1)")
            continue
        if mode == "apply":
            p.runs[0].text = newtext
        applied += 1
    # 子串替换
    sub_applied = 0
    for idx, pairs in SUBS.items():
        p = paras[idx]
        if not p.runs:
            problems.append(f"[SUB idx={idx}] 无 run")
            continue
        txt = p.runs[0].text
        for old, new in pairs:
            if old not in txt:
                problems.append(f"[SUB idx={idx}] 子串未找到: <{old[:24]}>")
                continue
            txt = txt.replace(old, new)
            sub_applied += 1
        if mode == "apply":
            p.runs[0].text = txt

    print(f"整段替换可用: {applied}/{len(FULL)}")
    print(f"子串替换可用: {sub_applied}")
    if problems:
        print("\n--- 需要关注的问题 ---")
        for x in problems:
            print(x)
    if mode == "apply" and not problems:
        d.save(SRC)
        print(f"\n已保存到 {SRC}")
    elif mode == "apply" and problems:
        print("\n存在问题，未保存。请先修正前缀/索引。")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "check")
